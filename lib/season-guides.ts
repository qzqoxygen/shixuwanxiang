export function isGuideMode(value: string | null): value is GuideMode {
  return value !== null && Object.hasOwn(GUIDE_MODES, value);
}

export function isGuideTopic(value: unknown): value is GuideTopic {
  return typeof value === "string" && Object.hasOwn(GUIDE_TOPICS, value);
}

export function readLiveGuide(value: unknown) {
  if (!value || typeof value !== "object" || !("guide" in value) || typeof value.guide !== "string") return null;
  const guide = value.guide.trim();
  return guide.length >= 15 && guide.length <= 250 && !/[\p{Cc}\p{Zl}\p{Zp}<>]|https?:\/\//iu.test(guide) ? guide : null;
}
